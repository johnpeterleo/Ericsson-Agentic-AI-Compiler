"""Create a working folder for Claude Code on one task: reference.py, candidate.py, check.py, PROMPT.md.

    python cc_setup.py <task> <folder>
"""
import sys
from pathlib import Path

REPO = Path.home() / "frozen-6a612ed"
sys.path.insert(0, str(REPO))
from src.agent.tasks import load_task
from src.agent.tool_prompts import CODE_RULES, GOAL, WHERE_SPEEDUPS_COME_FROM

PYTHON = Path.home() / "Ericsson-Agentic-AI-Compiler/.venv/bin/python"
TIME_LIMIT_MINUTES = 45

CHECK = '''"""Check candidate.py against the reference and time both on this GPU.

    {python} check.py

This is the same check the project's agents get: `candidate` must match `reference` on two
input cases (within the tolerance below), compile within 60 s, and is then timed against
the reference in alternating rounds. It prints the verdict and the speedup.
"""
import sys
from pathlib import Path

sys.path.insert(0, "{repo}")
from src.agent.search import EvaluationSettings, evaluate_on
from src.agent.tasks import load_task

TASK = "{task}"


def load_candidate():
    namespace = {{"__name__": "candidate"}}
    exec(Path(__file__).with_name("candidate.py").read_text(), namespace)
    return namespace["candidate"]


if __name__ == "__main__":
    task = load_task(TASK, "default")
    print(f"Inputs: {{task.input_summary()}}; tolerance rtol={{task.rtol}}, atol={{task.atol}}")
    result = evaluate_on(task, load_candidate(), EvaluationSettings())
    if result.correct:
        print(f"correct; reference {{result.reference_ms:.3f}} ms, candidate {{result.candidate_ms:.3f}} ms, "
              f"speedup {{result.speedup:.3f}}x")
    else:
        print(f"rejected at {{result.failure_stage}}: {{result.message}}")
'''

PROMPT = """{goal}

{where}

## Your task

The folder you are in holds:
- `reference.py`: the program to speed up. Its function `reference` is the ground truth. Do not edit this file.
- `candidate.py`: your rewrite. It must define `candidate`, taking the same arguments as `reference`. It starts as a copy of the reference.
- `check.py`: run `{python} check.py` to check `candidate` against the reference and time both on the GPU (an NVIDIA L4). Do not edit this file.

Inputs: {inputs}. Tolerance: rtol={rtol}, atol={atol}. JAX runs with its default settings.

{rules}
- `candidate.py` is run on its own, so it must import what it uses (for example `import jax` and `import jax.numpy as jnp`).

How it is scored: when you are done, `candidate.py` is checked again and timed on an input you have not seen. The speedup there is the result.

Work only inside this folder: do not read or search other folders in the home directory, and do not look up solutions online. You may write any scripts you like here, use the Python interpreter above, and read the installed JAX library. You have about {minutes} minutes. Finish by leaving your fastest correct version in `candidate.py`, and end with a short summary of what you tried and measured.
"""

if __name__ == "__main__":
    task_name, folder = sys.argv[1], Path(sys.argv[2])
    task = load_task(task_name, "default")
    folder.mkdir(parents=True)
    (folder / "reference.py").write_text(task.source_text)
    (folder / "candidate.py").write_text(task.source_text + "\n\ncandidate = reference\n")
    (folder / "check.py").write_text(CHECK.format(python=PYTHON, repo=REPO, task=task_name))
    (folder / "PROMPT.md").write_text(PROMPT.format(
        goal=GOAL, where=WHERE_SPEEDUPS_COME_FROM, python=PYTHON, inputs=task.input_summary(),
        rtol=task.rtol, atol=task.atol, rules=CODE_RULES, minutes=TIME_LIMIT_MINUTES,
    ))
    print(f"created {folder}")
